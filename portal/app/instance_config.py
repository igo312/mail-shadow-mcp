"""Generate the per-instance mail-shadow-mcp config.yaml.

The file is written into a dedicated named volume (never a host bind mount) and
mounted read-only into the instance container.  It contains the mailbox app
password, so the volume is only readable by the Docker daemon/root.
"""

from __future__ import annotations

import json
import re

from .providers import ImapSettings


def _quote(value: str) -> str:
    # JSON double-quoted strings are valid YAML double-quoted scalars and give
    # correct escaping for quotes, backslashes, tabs and Unicode.
    return json.dumps(value, ensure_ascii=False)


def render_instance_config(
    *,
    email: str,
    settings: ImapSettings,
    password: str,
    bearer_token: str,
    sync_interval_min: int = 5,
    sync_jitter_sec: int = 300,
    http_port: int = 8080,
    folders: tuple[str, ...] | list[str] | None = ("INBOX",),
    trash_folder: str = "",
    tls_skip_verify: bool = False,
) -> str:
    lines = [
        "# Generated by the mail-shadow-mcp hosting portal. Do not edit by hand.",
        "# This file contains an email app password; keep the config volume private.",
        f"sync_interval_min: {int(sync_interval_min)}",
        f"sync_jitter_sec: {int(sync_jitter_sec)}",
        "",
        "database:",
        '  path: "/data/mail.db"',
        "",
        'attachment_dir: "/data/attachments"',
        "",
        'log_level: "info"',
        'log_format: "text"',
        "",
        "transport: http",
        f'http_addr: ":{int(http_port)}"',
        f"http_bearer_token: {_quote(bearer_token)}",
        "",
        "accounts:",
        f"  - id: {_quote(email)}",
        f"    host: {_quote(settings.host)}",
        f"    port: {settings.port}",
        f"    username: {_quote(settings.username)}",
        f"    password: {_quote(password)}",
        f"    tls_mode: {_quote(settings.tls_mode)}",
        f"    tls_skip_verify: {'true' if tls_skip_verify else 'false'}",
    ]
    if folders:
        rendered = ", ".join(_quote(folder) for folder in folders)
        lines.append(f"    folders: [{rendered}]")
        if any(folder.upper() == "INBOX" for folder in folders):
            lines.append('    idle_folders: ["INBOX"]')
    if trash_folder:
        lines.append(f"    trash_folder: {_quote(trash_folder)}")
    lines.append("")
    return "\n".join(lines)


def _scalar(text: str, key: str) -> str:
    match = re.search(rf"(?m)^\s*{re.escape(key)}:\s*(.+?)\s*$", text)
    return match.group(1).strip() if match else ""


def _unquote(raw: str) -> str:
    if len(raw) >= 2 and raw[0] == '"' and raw[-1] == '"':
        try:
            value = json.loads(raw)
            return value if isinstance(value, str) else raw
        except json.JSONDecodeError:
            return raw
    return raw


def _int_value(raw: str, default: int) -> int:
    try:
        return int(raw)
    except (TypeError, ValueError):
        return default


def parse_instance_config(text: str) -> dict[str, object]:
    """Read the credentials back from a generated instance config.

    The portal deliberately does not store the mailbox password in its control
    database.  During an image upgrade the existing config volume is the only
    copy, so the migration command reads it back and renders a new config with
    the same password and bearer token.  No user action is required and the MCP
    token stays valid.
    """
    raw_token = _scalar(text, "http_bearer_token")
    raw_password = _scalar(text, "password")
    raw_skip_verify = _scalar(text, "tls_skip_verify").lower()
    return {
        "bearer_token": _unquote(raw_token),
        "password": _unquote(raw_password),
        "sync_interval_min": _int_value(_scalar(text, "sync_interval_min"), 0),
        "sync_jitter_sec": _int_value(_scalar(text, "sync_jitter_sec"), 0),
        "tls_skip_verify": raw_skip_verify == "true",
    }
