"""Generate the per-instance mail-shadow-mcp config.yaml.

The file is written into a dedicated named volume (never a host bind mount) and
mounted read-only into the instance container.  It contains the mailbox app
password, so the volume is only readable by the Docker daemon/root.
"""

from __future__ import annotations

import json

from .providers import ImapSettings


def _quote(value: str) -> str:
    # JSON double-quoted strings are valid YAML double-quoted scalars and give
    # correct escaping for quotes, backslashes, tabs and Unicode.
    return json.dumps(value, ensure_ascii=False)


def render_instance_config(
    *,
    email: str,
    settings: ImapSettings,
    password: str,
    bearer_token: str,
    sync_interval_min: int = 5,
    http_port: int = 8080,
) -> str:
    lines = [
        "# Generated by the mail-shadow-mcp hosting portal. Do not edit by hand.",
        "# This file contains an email app password; keep the config volume private.",
        f"sync_interval_min: {int(sync_interval_min)}",
        "",
        "database:",
        '  path: "/data/mail.db"',
        "",
        'attachment_dir: "/data/attachments"',
        "",
        'log_level: "info"',
        'log_format: "text"',
        "",
        "transport: http",
        f'http_addr: ":{int(http_port)}"',
        f"http_bearer_token: {_quote(bearer_token)}",
        "",
        "accounts:",
        f"  - id: {_quote(email)}",
        f"    host: {_quote(settings.host)}",
        f"    port: {settings.port}",
        f"    username: {_quote(settings.username)}",
        f"    password: {_quote(password)}",
        f"    tls_mode: {_quote(settings.tls_mode)}",
        "    tls_skip_verify: false",
        '    idle_folders: ["INBOX"]',
        "",
    ]
    return "\n".join(lines)
